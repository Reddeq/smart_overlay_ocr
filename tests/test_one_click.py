"""Contract tests for the default one-click conversion workflow.

All network, heavy OCR and Office generation are isolated; the repository's
existing export and grouping suites exercise their concrete implementations.
"""
from pathlib import Path

import pytest

from smart_overlay.diagnose_vl import synthetic
from smart_overlay.input import open_project
from smart_overlay.one_click import (
    ProcessingCancelled, available_pptx, convert_drawing,
    is_standalone_designation, suppress_standalone_codes,
)
from smart_overlay.settings import Settings
from smart_overlay.structure import merge_texts, validate_project


@pytest.fixture
def setup_conversion(monkeypatch, tmp_path):
    source = tmp_path / "drawing.png"
    source.write_bytes(b"placeholder: heavy image OCR is mocked")
    project, _ = synthetic()
    monkeypatch.setattr("smart_overlay.one_click.load_image", lambda path: project.model_copy(deep=True))
    monkeypatch.setattr("smart_overlay.one_click.local_ocr",
                        lambda source, settings, progress: source.model_copy(deep=True))
    monkeypatch.setattr("smart_overlay.one_click.data_dir", lambda: tmp_path / "local-app-data")
    generated = []

    def export(project, output, settings, *, allow_unreviewed):
        validate_project(project)
        assert allow_unreviewed
        generated.append(project.model_copy(deep=True))
        Path(output).write_bytes(b"pptx generated by mock")

    monkeypatch.setattr("smart_overlay.one_click.export_pptx", export)
    return source, generated


@pytest.mark.parametrize("text,expected", [
    ("123", True), ("12,5", True), ("XS1", True),
    ("D38999/26WA35PN", True), ("A10", True),
    ("Вилка D38999/26WA35PN", False),
    ("Вилка\nD38999/26WA35PN", False),
    ("Кассета 1", False), ("ВКЛ", False), ("Valve", False),
])
def test_designations_are_not_exported_as_standalone_frames(text, expected):
    assert bool(is_standalone_designation(text)) is expected


def test_only_standalone_codes_excluded_after_merging():
    project, _ = synthetic()
    project.objects[0].text = "XS1"
    assert suppress_standalone_codes(project) == 1
    assert project.objects[0].excluded
    assert all(not obj.excluded for obj in project.objects[1:])
    validate_project(project)


def test_does_not_overwrite_previous_pptx(tmp_path):
    source = tmp_path / "drawing.png"
    first = tmp_path / "drawing.pptx"
    first.write_bytes(b"previous translation")
    assert available_pptx(source) == tmp_path / "drawing-01.pptx"
    (tmp_path / "drawing-01.pptx").write_bytes(b"another")
    assert available_pptx(source) == tmp_path / "drawing-02.pptx"
    assert first.read_bytes() == b"previous translation"


def test_local_one_click_exports_and_retains_editable_project(setup_conversion, monkeypatch):
    source, exports = setup_conversion
    monkeypatch.setattr("smart_overlay.one_click._smart",
                        lambda *a, **kw: pytest.fail("API must be opt-in"))
    result = convert_drawing(source, settings=Settings(), api_key="secret", consent=False)
    assert result.pptx.exists()
    assert result.pptx.read_bytes() == b"pptx generated by mock"
    assert result.project_file.exists()
    assert open_project(result.project_file) == result.project
    assert exports and len(exports[0].objects) == 5
    assert any("нет согласия" in warning for warning in result.warnings)


def test_cloud_pipeline_proposals_are_consumed_before_export(setup_conversion, monkeypatch):
    source, exports = setup_conversion
    called = []

    def smart(project, settings, api_key, proxy, progress, cancelled, warnings, max_requests):
        called.append((api_key, proxy, max_requests))
        merge_texts(project, [project.objects[i].id for i in range(3)])
        return project, 1, 0

    monkeypatch.setattr("smart_overlay.one_click._smart", smart)
    result = convert_drawing(source, settings=Settings(), api_key="secret",
                             consent=True, proxy="http://127.0.0.1:10809")
    assert called == [("secret", "http://127.0.0.1:10809", 24)]
    assert len(result.project.objects) == 3
    assert len(exports[0].objects) == 3


def test_vl_error_keeps_local_result_and_exports(setup_conversion, monkeypatch):
    source, exports = setup_conversion
    def error(*args, **kwargs):
        raise RuntimeError("broken upstream")
    monkeypatch.setattr("smart_overlay.one_click._smart", error)
    result = convert_drawing(source, settings=Settings(), api_key="secret", consent=True)
    assert result.pptx.exists()
    assert len(exports[0].objects) == 5
    assert result.needs_review == 5
    assert any("локальный результат" in w for w in result.warnings)


def test_cancellation_never_creates_pptx(setup_conversion):
    source, exports = setup_conversion
    with pytest.raises(ProcessingCancelled):
        convert_drawing(source, cancelled=lambda: True)
    assert not source.with_suffix(".pptx").exists()
    assert not exports


def test_quick_window_shows_primary_actions(gui_app, monkeypatch):
    from smart_overlay.quick_app import QuickWindow
    monkeypatch.setattr("smart_overlay.quick_app.load_settings", lambda: Settings())
    window = QuickWindow()
    try:
        assert window.run_button.text() == "Распознать → PPTX"
        assert not window.run_button.isEnabled()
        assert not window.open_pptx.isVisible()
        assert not window.review.isVisible()
    finally:
        window.close()
        window.deleteLater()
